// Writes the Rune icon catalog: every icon src/renderer/components/icons
// exports, rendered by React exactly as the web client renders it, and every
// Material Icon Theme file-type icon with the manifest that picks one for a
// file or folder name, as file-explorer/material-icon-resolver.ts does.
//   bun scripts/rune/gen-icons.ts          rewrite the files
//   bun scripts/rune/gen-icons.ts --check  exit 1 when a committed file is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { generateManifest, type Manifest } from 'material-icon-theme'
import { createElement, type ElementType } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'

const ROOT = join(import.meta.dir, '..', '..')
const ICONS_DIR = join(ROOT, 'apps/rune/crates/theme/assets/icons')
const APP_ICONS_RS = join(ICONS_DIR, 'app.rs')
const FILE_ICONS_RS = join(ICONS_DIR, 'file_types.rs')
const MATERIAL_DIR = join(ROOT, 'node_modules/material-icon-theme/icons')

/** Root attributes the elements inherit; the rest (size, aria, class) do not paint. */
const PAINT_ATTRS = [
  'fill',
  'fill-rule',
  'clip-rule',
  'stroke',
  'stroke-width',
  'stroke-linecap',
  'stroke-linejoin',
  'opacity'
]

interface Icon {
  name: string
  view: number
  body: string
}

/** Splits `<svg ...>body</svg>` into a view size and a body that keeps the root's paint. */
function parseSvg(name: string, svg: string): Icon {
  const match = /<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/.exec(svg.trim())
  if (!match) throw new Error(`${name}: not an <svg> document`)
  const [, attrs, inner] = match
  const box = /\bviewBox="([^"]+)"/
    .exec(attrs)?.[1]
    .trim()
    .split(/[\s,]+/)
    .map(Number)
  if (box?.length !== 4 || box.some((v) => !Number.isFinite(v))) {
    throw new Error(`${name}: no viewBox`)
  }
  // Rune icons sit in a square viewBox at the origin; centre any other box in one.
  const [x, y, w, h] = box
  const view = Math.max(w, h)
  const dx = (view - w) / 2 - x
  const dy = (view - h) / 2 - y
  const paint = PAINT_ATTRS.flatMap((attr) => {
    const value = new RegExp(`(?:^|\\s)${attr}="([^"]*)"`).exec(attrs)?.[1]
    return value === undefined ? [] : [`${attr}="${value}"`]
  })
  if (dx !== 0 || dy !== 0) paint.push(`transform="translate(${dx} ${dy})"`)
  const body = inner.trim()
  return { name, view, body: paint.length > 0 ? `<g ${paint.join(' ')}>${body}</g>` : body }
}

function screamingSnake(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^(\d)/, '_$1')
    .toUpperCase()
}

function rawString(name: string, body: string): string {
  if (body.includes('"##')) throw new Error(`${name}: body contains "##`)
  return `r##"${body}"##`
}

function iconStatic(ident: string, icon: Icon, visibility: string): string {
  return `${visibility}static ${ident}: Icon = Icon { name: "${icon.name}", view: ${icon.view.toFixed(1)}, body: ${rawString(icon.name, icon.body)} };`
}

async function appIconsRust(): Promise<string> {
  const exports = (await import('../../src/renderer/components/icons/index.tsx')) as Record<
    string,
    unknown
  >
  const canonical = new Map<unknown, string>()
  const names = Object.keys(exports).sort()
  for (const name of names) {
    const component = exports[name] as { displayName?: string; render?: { name?: string } }
    const own = component.displayName ?? component.render?.name
    if (!canonical.has(component) || own === name) canonical.set(component, name)
  }
  const statics: string[] = []
  for (const [component, name] of [...canonical].sort(([, a], [, b]) => a.localeCompare(b))) {
    const svg = renderToStaticMarkup(createElement(component as ElementType))
    statics.push(iconStatic(screamingSnake(name), parseSvg(name, svg), 'pub '))
  }
  const byName = names.map(
    (name) => `    ("${name}", &${screamingSnake(canonical.get(exports[name]) as string)}),`
  )
  return `// Generated by scripts/rune/gen-icons.ts from src/renderer/components/icons. Do not edit.
${statics.join('\n')}

/// Every export of \`components/icons\` by its name, aliases included, sorted.
pub(crate) static BY_NAME: &[(&str, &Icon)] = &[
${byName.join('\n')}
];
`
}

type NameMap = Record<string, string> | undefined

function lightManifest(base: Manifest): Manifest {
  const light = base.light ?? {}
  const merge = (a: NameMap, b: NameMap) => ({ ...a, ...b })
  return {
    ...base,
    fileExtensions: merge(base.fileExtensions, light.fileExtensions),
    fileNames: merge(base.fileNames, light.fileNames),
    folderNames: merge(base.folderNames, light.folderNames),
    folderNamesExpanded: merge(base.folderNamesExpanded, light.folderNamesExpanded),
    rootFolderNames: merge(base.rootFolderNames, light.rootFolderNames),
    rootFolderNamesExpanded: merge(base.rootFolderNamesExpanded, light.rootFolderNamesExpanded)
  }
}

function fileIconsRust(): string {
  const dark = generateManifest()
  const light = lightManifest(dark)
  const keys = Object.keys(dark.iconDefinitions ?? {}).sort()
  const index = new Map(keys.map((key, i) => [key, i]))
  const statics = keys.map((key) => {
    const file = (dark.iconDefinitions?.[key]?.iconPath ?? '').split(/[/\\]/).pop() ?? ''
    const svg = readFileSync(join(MATERIAL_DIR, file), 'utf8')
    return iconStatic(`I${index.get(key)}`, parseSvg(key, svg), '')
  })
  const table = (ident: string, map: NameMap) => {
    const rows = Object.entries(map ?? {})
      .map(([name, key]): [string, string] => {
        if (!index.has(key)) throw new Error(`${ident}: ${name} names unknown icon ${key}`)
        return [name, key]
      })
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
      .map(([name, key]) => `    (${JSON.stringify(name)}, ${index.get(key)}),`)
    return `pub(crate) static ${ident}: &[(&str, u16)] = &[\n${rows.join('\n')}\n];`
  }
  const tables = (prefix: string, m: Manifest) =>
    [
      table(`${prefix}_FILE_NAMES`, m.fileNames),
      table(`${prefix}_FILE_EXTENSIONS`, m.fileExtensions),
      table(`${prefix}_FOLDER_NAMES`, m.folderNames),
      table(`${prefix}_FOLDER_NAMES_EXPANDED`, m.folderNamesExpanded),
      table(`${prefix}_ROOT_FOLDER_NAMES`, m.rootFolderNames),
      table(`${prefix}_ROOT_FOLDER_NAMES_EXPANDED`, m.rootFolderNamesExpanded)
    ].join('\n')
  const fallback = (key: string | undefined, name: string) => {
    const i = index.get(key ?? name)
    if (i === undefined) throw new Error(`manifest has no ${key ?? name} icon`)
    return i
  }
  return `// Generated by scripts/rune/gen-icons.ts from material-icon-theme. Do not edit.
${statics.join('\n')}

/// Every file-type icon, sorted by its Material Icon Theme key.
pub(crate) static ALL: &[&Icon] = &[${keys.map((_, i) => `&I${i}`).join(', ')}];

pub(crate) const FILE: u16 = ${fallback(dark.file, 'file')};
pub(crate) const FOLDER: u16 = ${fallback(dark.folder, 'folder')};
pub(crate) const FOLDER_EXPANDED: u16 = ${fallback(dark.folderExpanded, 'folder-open')};
pub(crate) const ROOT_FOLDER: u16 = ${fallback(dark.rootFolder, 'folder-root')};
pub(crate) const ROOT_FOLDER_EXPANDED: u16 = ${fallback(dark.rootFolderExpanded, 'folder-root-open')};

${tables('DARK', dark)}
${tables('LIGHT', light)}
`
}

async function generateIconFiles(): Promise<Map<string, string>> {
  return new Map([
    [APP_ICONS_RS, await appIconsRust()],
    [FILE_ICONS_RS, fileIconsRust()]
  ])
}

if (import.meta.main) {
  const files = await generateIconFiles()
  if (process.argv.includes('--check')) {
    const stale = [...files].filter(([p, c]) => !existsSync(p) || readFileSync(p, 'utf8') !== c)
    for (const [path] of stale) console.error(`stale: ${path}`)
    if (stale.length > 0) {
      console.error('Run: bun scripts/rune/gen-icons.ts')
      process.exit(1)
    }
  } else {
    for (const [path, content] of files) writeFileSync(path, content)
    console.log(`wrote ${files.size} files`)
  }
}
