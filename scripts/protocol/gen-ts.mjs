#!/usr/bin/env node
// Turns crates/troupe-protocol/schema/protocol.schema.json into
// src/shared/types/generated/protocol.ts.
//   node scripts/protocol/gen-ts.mjs          write the file
//   node scripts/protocol/gen-ts.mjs --check  exit 1 when the committed file is stale
import { spawnSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
export const SCHEMA_PATH = join(ROOT, 'crates/troupe-protocol/schema/protocol.schema.json')
export const OUTPUT_PATH = join(ROOT, 'src/shared/types/generated/protocol.ts')

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/

function refName(ref) {
  const prefix = '#/$defs/'
  if (!ref.startsWith(prefix)) throw new Error(`unsupported $ref ${ref}`)
  return ref.slice(prefix.length)
}

const LITERAL_ESCAPES = {
  '\\': '\\\\',
  "'": "\\'",
  '\n': '\\n',
  '\r': '\\r',
  '\u2028': '\\u2028',
  '\u2029': '\\u2029'
}

function literal(value) {
  return typeof value === 'string'
    ? `'${value.replace(/[\\'\n\r\u2028\u2029]/g, (char) => LITERAL_ESCAPES[char])}'`
    : JSON.stringify(value)
}

function union(parts) {
  const unique = [...new Set(parts)]
  return unique.length === 1 ? unique[0] : unique.map(wrap).join(' | ')
}

function wrap(type) {
  return /[|&]/.test(type) && !/^[{(]/.test(type) ? `(${type})` : type
}

function comment(text, indent) {
  if (!text) return ''
  const lines = text.split('\n')
  if (lines.length === 1) return `${indent}/** ${lines[0]} */\n`
  return `${indent}/**\n${lines.map((line) => `${indent} * ${line}`.trimEnd()).join('\n')}\n${indent} */\n`
}

function objectType(schema, indent) {
  const required = new Set(schema.required ?? [])
  const inner = `${indent}  `
  const lines = Object.entries(schema.properties ?? {}).map(([key, value]) => {
    const name = IDENTIFIER.test(key) ? key : literal(key)
    const optional = required.has(key) ? '' : '?'
    return `${comment(value.description, inner)}${inner}${name}${optional}: ${toType(value, inner)}`
  })
  const extra = schema.additionalProperties
  if (extra === true) lines.push(`${inner}[key: string]: unknown`)
  else if (extra && typeof extra === 'object')
    lines.push(`${inner}[key: string]: ${toType(extra, inner)}`)
  return lines.length === 0 ? 'Record<string, never>' : `{\n${lines.join('\n')}\n${indent}}`
}

function toType(schema, indent = '') {
  if (schema === true) return 'unknown'
  if (schema === false) return 'never'
  if (schema.$ref) return refName(schema.$ref)
  if ('const' in schema) return literal(schema.const)
  if (schema.enum) return union(schema.enum.map(literal))
  const variants = schema.oneOf ?? schema.anyOf
  if (variants) {
    const choice = union(variants.map((variant) => toType(variant, indent)))
    return schema.properties ? `${objectType(schema, indent)} & (${choice})` : choice
  }
  if (schema.allOf) return schema.allOf.map((part) => wrap(toType(part, indent))).join(' & ')
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : []
  if (types.length === 0) return 'unknown'
  return union(
    types.map((type) => {
      switch (type) {
        case 'null':
          return 'null'
        case 'string':
          return 'string'
        case 'integer':
        case 'number':
          return 'number'
        case 'boolean':
          return 'boolean'
        case 'array':
          return `Array<${toType(schema.items ?? true, indent)}>`
        case 'object':
          return objectType(schema, indent)
        default:
          throw new Error(`unsupported type ${type}`)
      }
    })
  )
}

export function generate(schema) {
  const out = [
    '// Generated by scripts/protocol/gen-ts.mjs from',
    '// crates/troupe-protocol/schema/protocol.schema.json. Do not edit.',
    ''
  ]
  for (const [name, value] of Object.entries(schema['x-constants'] ?? {})) {
    out.push(`export const ${name} = ${literal(value)}`)
  }
  for (const name of Object.keys(schema.$defs).sort()) {
    const def = schema.$defs[name]
    out.push('')
    out.push(`${comment(def.description, '')}export type ${name} = ${toType(def)}`)
    if (Array.isArray(def.enum) && def.enum.every((value) => typeof value === 'string')) {
      out.push('')
      out.push(`export const ${name}Values = [${def.enum.map(literal).join(', ')}] as const`)
    }
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`
}

/** Biome's layout when the repo's Biome is installed; the check ignores layout. */
export function format(text) {
  const biome = join(ROOT, 'node_modules', '.bin', 'biome')
  if (!existsSync(biome)) return text
  const result = spawnSync(biome, ['format', `--stdin-file-path=${OUTPUT_PATH}`], {
    cwd: ROOT,
    input: text,
    encoding: 'utf8'
  })
  if (result.status !== 0) throw new Error(`biome format failed: ${result.stderr}`)
  return result.stdout
}

/** Layout-free form of a generated file: comments and whitespace dropped,
 * while string literals keep every character. */
export function normalize(text) {
  let out = ''
  let i = 0
  while (i < text.length) {
    const char = text[i]
    if (char === "'" || char === '"' || char === '`') {
      let end = i + 1
      while (end < text.length && text[end] !== char) end += text[end] === '\\' ? 2 : 1
      out += text.slice(i, end + 1)
      i = end + 1
    } else if (char === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i += 1
    } else if (char === '/' && text[i + 1] === '*') {
      const close = text.indexOf('*/', i + 2)
      i = close === -1 ? text.length : close + 2
    } else if (/[\s;,]/.test(char)) {
      i += 1
    } else {
      out += char === '|' && /[=:<(]/.test(out.at(-1) ?? '') ? '' : char
      i += 1
    }
  }
  return out
}

function main() {
  const fresh = generate(JSON.parse(readFileSync(SCHEMA_PATH, 'utf8')))
  if (process.argv.includes('--check')) {
    const committed = existsSync(OUTPUT_PATH) ? readFileSync(OUTPUT_PATH, 'utf8') : ''
    if (normalize(committed) !== normalize(fresh)) {
      console.error(`${OUTPUT_PATH} is stale; run node scripts/protocol/gen-ts.mjs`)
      process.exit(1)
    }
    return
  }
  mkdirSync(dirname(OUTPUT_PATH), { recursive: true })
  writeFileSync(OUTPUT_PATH, format(fresh))
  console.log(`wrote ${OUTPUT_PATH}`)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main()
