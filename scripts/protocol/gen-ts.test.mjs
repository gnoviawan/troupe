import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'
import { generate, normalize, OUTPUT_PATH, SCHEMA_PATH } from './gen-ts.mjs'

const schema = () => JSON.parse(readFileSync(SCHEMA_PATH, 'utf8'))

test('the committed protocol.ts matches the committed schema', () => {
  const committed = readFileSync(OUTPUT_PATH, 'utf8')
  assert.equal(
    normalize(committed),
    normalize(generate(schema())),
    'src/shared/types/generated/protocol.ts is stale; run node scripts/protocol/gen-ts.mjs'
  )
})

test('a schema change makes the committed file stale', () => {
  const changed = schema()
  changed.$defs.WsGapFrame.properties.extra = { type: 'string' }
  const committed = readFileSync(OUTPUT_PATH, 'utf8')
  assert.notEqual(normalize(committed), normalize(generate(changed)))
})

test('schema shapes map to TypeScript', () => {
  const ts = generate({
    'x-constants': { V: 7 },
    $defs: {
      Tag: { type: 'string', enum: ['a', 'b'] },
      Frame: {
        type: 'object',
        properties: {
          kind: { type: 'string', const: 'gap' },
          sid: { type: ['string', 'null'] },
          seq: { type: 'integer' },
          tags: { type: 'array', items: { $ref: '#/$defs/Tag' } },
          extra: true
        },
        required: ['kind', 'sid'],
        additionalProperties: true
      }
    }
  })
  assert.equal(
    ts,
    [
      '// Generated by scripts/protocol/gen-ts.mjs from',
      '// crates/troupe-protocol/schema/protocol.schema.json. Do not edit.',
      '',
      'export const V = 7',
      '',
      'export type Frame = {',
      "  kind: 'gap'",
      '  sid: string | null',
      '  seq?: number',
      '  tags?: Array<Tag>',
      '  extra?: unknown',
      '  [key: string]: unknown',
      '}',
      '',
      "export type Tag = 'a' | 'b'",
      '',
      "export const TagValues = ['a', 'b'] as const",
      ''
    ].join('\n')
  )
})
