/**
 * Dumps the cells `@xterm/headless` holds at each checkpoint of the PTY
 * recordings `term-record.py` wrote, and the character width table the React
 * terminal uses, for the Rune terminal's cell model (`apps/rune/crates/term`).
 *
 *   bun tools/parity/depth/term-cells.ts cells apps/rune/crates/term/tests/fixtures
 *   bun tools/parity/depth/term-cells.ts widths apps/rune/crates/term/src/width_table.rs
 *
 * The terminal is built with the React client's options (`terminal-config.ts`):
 * 10000 lines of scrollback, tab stops every 4 columns, no EOL conversion.
 *
 * A dump line lists its cells up to the last one that is not a blank default
 * cell. A cell is `[chars, width, fg, bg, flags]`: `chars` is empty for a blank
 * cell or the right half of a wide one, a colour is `"d"` (default), a palette
 * index, or `"#rrggbb"`, and `flags` is a bit set in `FLAGS` order.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import xterm from '@xterm/headless'

const { Terminal } = xterm

interface Meta {
  cols: number
  rows: number
  checkpoints: number[]
}

type Color = 'd' | number | string
type Cell = [string, number, Color, Color, number]

interface XtermCell {
  getChars(): string
  getWidth(): number
  isFgDefault(): boolean
  isBgDefault(): boolean
  isFgRGB(): boolean
  isBgRGB(): boolean
  getFgColor(): number
  getBgColor(): number
  [flag: string]: unknown
}

const FLAGS = [
  'isBold',
  'isDim',
  'isItalic',
  'isUnderline',
  'isBlink',
  'isInverse',
  'isInvisible',
  'isStrikethrough',
  'isOverline'
] as const

const OPTIONS = { scrollback: 10000, tabStopWidth: 4, convertEol: false, allowProposedApi: true }

function color(isDefault: boolean, isRgb: boolean, value: number): Color {
  if (isDefault) return 'd'
  if (isRgb) return `#${value.toString(16).padStart(6, '0')}`
  return value
}

function cell(c: XtermCell): Cell {
  let flags = 0
  FLAGS.forEach((name, bit) => {
    if ((c[name] as () => number)()) flags |= 1 << bit
  })
  return [
    c.getChars(),
    c.getWidth(),
    color(c.isFgDefault(), c.isFgRGB(), c.getFgColor()),
    color(c.isBgDefault(), c.isBgRGB(), c.getBgColor()),
    flags
  ]
}

function blank(c: Cell): boolean {
  return c[0] === '' && c[1] === 1 && c[2] === 'd' && c[3] === 'd' && c[4] === 0
}

function dump(term: any, offset: number) {
  const buffer = term.buffer.active
  const lines = []
  for (let y = 0; y < buffer.length; y++) {
    const line = buffer.getLine(y)
    const cells: Cell[] = []
    for (let x = 0; x < term.cols; x++) cells.push(cell(line.getCell(x)))
    while (cells.length > 0 && blank(cells[cells.length - 1])) cells.pop()
    lines.push({ wrapped: line.isWrapped, cells })
  }
  const core = term._core.coreService
  return {
    offset,
    buffer: buffer.type,
    cursor: [buffer.cursorX, buffer.cursorY],
    cursorHidden: core.isCursorHidden,
    cursorStyle: core.decPrivateModes.cursorStyle ?? null,
    cursorBlink: core.decPrivateModes.cursorBlink ?? null,
    modes: term.modes,
    lines
  }
}

function write(term: InstanceType<typeof Terminal>, bytes: Uint8Array): Promise<void> {
  return new Promise((resolve) => term.write(bytes, resolve))
}

async function cells(dir: string) {
  for (const file of readdirSync(dir).filter((f) => f.endsWith('.bin'))) {
    const name = file.slice(0, -4)
    const meta = JSON.parse(readFileSync(join(dir, `${name}.json`), 'utf8')) as Meta
    const bytes = new Uint8Array(readFileSync(join(dir, file)))
    const term = new Terminal({ ...OPTIONS, cols: meta.cols, rows: meta.rows })
    const checkpoints = []
    let fed = 0
    for (const offset of meta.checkpoints) {
      await write(term, bytes.subarray(fed, offset))
      fed = offset
      checkpoints.push(dump(term, offset))
    }
    const out = join(dir, `${name}.cells.json`)
    writeFileSync(out, `${JSON.stringify({ cols: meta.cols, rows: meta.rows, checkpoints })}\n`)
    console.log(`${out}: ${checkpoints.length} checkpoints`)
  }
}

/** Ranges of code points xterm draws 0 or 2 columns wide; every other is 1. */
function widths(out: string) {
  const term = new Terminal(OPTIONS)
  const unicode = (term as any)._core.unicodeService
  const ranges: Record<0 | 2, [number, number][]> = { 0: [], 2: [] }
  for (let cp = 0x20; cp <= 0x10ffff; cp++) {
    const w = unicode.wcwidth(cp) as number
    if (w !== 0 && w !== 2) continue
    const list = ranges[w]
    const last = list[list.length - 1]
    if (last && last[1] === cp - 1) last[1] = cp
    else list.push([cp, cp])
  }
  const table = (name: string, list: [number, number][]) =>
    `pub(crate) const ${name}: &[(u32, u32)] = &[\n${list
      .map(([a, b]) => `    (0x${a.toString(16)}, 0x${b.toString(16)}),`)
      .join('\n')}\n];\n`
  const header = `// Generated by tools/parity/depth/term-cells.ts from @xterm/headless ${term.unicode.activeVersion === '6' ? '(Unicode 6 widths)' : ''}. Do not edit.\n//! The column widths the React terminal (xterm.js) gives code points from U+0020 up: these\n//! ranges are 0 or 2 columns wide, every other code point 1.\n\n`
  writeFileSync(out, `${header}${table('ZERO', ranges[0])}\n${table('WIDE', ranges[2])}`)
  console.log(`${out}: ${ranges[0].length} zero-width and ${ranges[2].length} wide ranges`)
}

const [mode, target] = process.argv.slice(2)
if (mode === 'cells' && target) await cells(target)
else if (mode === 'widths' && target) widths(target)
else {
  console.error('usage: term-cells.ts cells <fixtures dir> | widths <width_table.rs>')
  process.exit(2)
}
